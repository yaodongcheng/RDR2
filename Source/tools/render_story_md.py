GENERIC = {
    'cs_genstorymale': '通用剧情男',
    'cs_genstoryfemale': '通用剧情女',
}


def clean_cast(name):
    if name in GENERIC:
        return GENERIC[name]
    if name.startswith('cs_genstory'):
        return GENERIC.get('cs_genstorymale' if 'male' in name else 'cs_genstoryfemale', '通用剧情角色')
    if name.startswith('cs_'):
        s = re.sub(r'_(ms1|fs1)$', '', name[3:])
        return '（角色型）' + s
    if name.startswith('player_'):
        return name
    if re.fullmatch(r'[a-z0-9_]+', name):
        return '（角色型）' + name
    return name


